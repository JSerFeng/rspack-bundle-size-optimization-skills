#!/usr/bin/env node
const { parseArgs } = require('node:util');
const { fail, json, openIndex } = require('./lib/common.cjs');
const { buildIndex } = require('./lib/index.cjs');
const { runQuery, MODULE_SORT } = require('./lib/queries.cjs');

const COMMON = ['db', 'run', 'scope'];
const PAGE = ['limit', 'cursor', 'sort'];
const COMMANDS = {
  index: ['coverage', 'usage', 'out'],
  describe: ['command'], status: [],
  modules: [...PAGE, 'search', 'package', 'fields'], module: ['module', 'include'],
  sources: [...PAGE, 'module'], exports: [...PAGE, 'module', 'used'],
  coverage: [...PAGE, 'module', 'source', 'view', 'state'],
  references: [...PAGE, 'module', 'direction', 'export', 'export-path', 'relation'],
  chain: ['module', 'export', 'export-path', 'depth', 'max-edges'],
  source: ['source', 'module', 'line', 'column', 'characters', 'map-source'],
  reference: ['edge', 'context', 'characters', 'line', 'column', 'space', 'column-base'],
  gaps: [...PAGE, 'module', 'kind'],
};
function describe(command) {
  if (command && !Object.hasOwn(COMMANDS, command)) fail('INVALID_ARGUMENT', 'Unknown command for describe.');
  return { ok: true, schemaVersion: 1, name: 'rspack-bundle-query',
    usage: 'node <skill>/scripts/query.cjs <command> [--db <index.sqlite>] [options]',
    commands: command ? { [command]: COMMANDS[command] } : COMMANDS,
    commonOptions: COMMON,
    moduleSortFields: Object.keys(MODULE_SORT),
    listSortFields: { sources: ['id', 'path'], exports: ['id', 'name', 'usage.incomingReferences'], coverageLines: ['id', 'line', 'generatedBytes', 'unexecutedBytes', 'coverage.generated.unexecutedBytes'], references: ['id'], gaps: ['id'] },
    required: { index: ['--coverage or --usage', 'out'], module: ['module'], sources: ['module'], exports: ['module'], coverage: ['module'], references: ['module'], chain: ['module', '--export-path or --export'], source: ['source'], reference: ['edge'] },
    defaults: { scope: 'build', sort: 'id:asc', limit: 20, maxLimit: 200, characters: 4000, maxCharacters: 12000, depth: 5, maxDepth: 20, maxEdges: 100, maxEdgeLimit: 500, outputBytes: 32768 },
    types: { limit: 'integer 1..200', depth: 'integer 1..20', 'max-edges': 'integer 1..500', characters: 'integer 1..12000', context: 'integer 0..10', line: 'integer >=1', column: 'integer >=0', 'column-base': 'integer 0..1', 'export-path': 'JSON string[]', otherOptions: 'string' },
    parameters: { sort: 'Comma-separated whitelist fields with :asc or :desc; null values sort last; ties use ID.',
      cursor: 'Opaque continuation; repeat the same dataset, run, scope, filters, sort and fields. Limit may change.',
      module: 'Exact moduleId returned by modules, not a filename.',
      'export-path': 'JSON array of names. --export instead selects one literal name, including dots.',
      fields: 'Comma-separated module fields. moduleId is always returned.',
      scope: 'build or loaded for current coverage input; unsupported asset-level scopes fail explicitly.',
      line: '1-based source line.', column: '0-based UTF-16 column.',
      source: 'Captured sourceId returned by module/sources. --map-source selects one captured loader map source.',
      relation: 'all (default), native, or module-graph; export filters default to native.',
      coverage: 'rspack-coverage Agent data directory (dataset schema 1, snapshot/report v2).',
      usage: 'Standalone usage SQLite snapshot, schema 1, status complete.',
    },
    semantics: { coverage: 'Recording evidence only, not proof of removable code or gzip savings.', usage: 'Compiler relations and export states, not observed function execution.', sourceLines: 'Coverage lines contain mapped generated byte counts; retainedSource totals count original-source line bytes.',
      ranges: 'Generated offset-to-source ranges are unavailable in current input format; source-line evidence remains queryable.' },
    errors: ['INVALID_ARGUMENT', 'INVALID_SORT', 'INVALID_INPUT', 'INVALID_INDEX', 'OUTPUT_EXISTS', 'INPUT_CHANGED', 'INPUT_IDENTITY_MISMATCH', 'CURSOR_MISMATCH', 'METRIC_UNAVAILABLE', 'FEATURE_UNAVAILABLE', 'MODULE_NOT_FOUND', 'SOURCE_UNAVAILABLE', 'REFERENCE_NOT_FOUND', 'RECORD_TOO_LARGE'],
  };
}
function main(argv = process.argv.slice(2)) {
  const names = [...new Set([...COMMON, ...Object.values(COMMANDS).flat()])];
  let parsed;
  try { parsed = parseArgs({ args: argv, allowPositionals: true,
    options: { ...Object.fromEntries(names.map(name => [name, { type: 'string' }])), help: { type: 'boolean', short: 'h' } } }); }
  catch (error) { fail('INVALID_ARGUMENT', error.message); }
  const { values, positionals } = parsed;
  if (values.help || !positionals.length) return describe();
  if (positionals.length !== 1 || !Object.hasOwn(COMMANDS, positionals[0])) fail('INVALID_ARGUMENT', 'Use describe to discover commands.');
  const command = positionals[0]; const allowed = command === 'index' || command === 'describe' ? COMMANDS[command] : [...COMMON, ...COMMANDS[command]];
  for (const name of Object.keys(values)) if (!allowed.includes(name)) fail('INVALID_ARGUMENT', `--${name} is not supported by ${command}.`);
  if (command === 'describe') return describe(values.command);
  if (command === 'index') return buildIndex(values);
  if (!values.db) fail('INVALID_ARGUMENT', '--db is required.');
  const ctx = { ...openIndex(values.db), command, args: values };
  try {
    const data = runQuery(ctx);
    const result = { ok: true, schemaVersion: 1, datasetId: ctx.meta.datasetId, buildId: ctx.meta.buildId, compiler: ctx.meta.compiler,
      coverageRunId: ctx.meta.coverageRunId, scenario: ctx.meta.scenario,
      gaps: { count: ctx.meta.counts.gaps, command: 'gaps' },
      query: { resource: command, scope: values.scope || 'build', ...(values.sort ? { sort: values.sort } : {}) },
      ...data };
    if (Buffer.byteLength(json(result)) > 32768) fail('RECORD_TOO_LARGE', 'Response exceeds 32 KiB. Request fewer fields or smaller source/graph budgets.');
    return result;
  } finally { ctx.db.close(); }
}
if (require.main === module) {
  try { process.stdout.write(`${json(main())}\n`); }
  catch (error) {
    process.stdout.write(`${json({ ok: false, schemaVersion: 1, error: { code: error.code || 'QUERY_FAILED', message: error.message, ...(error.details === undefined ? {} : { details: error.details }) } })}\n`);
    process.exitCode = 1;
  }
}
module.exports = { main, describe };
