const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { DatabaseSync } = require('node:sqlite');
const { encode } = require('@jridgewell/sourcemap-codec');
const { createCapture, setMeta, hash } = require('../lib/capture-store.cjs');
const { main } = require('../query.cjs');
const { coveredRanges } = require('../lib/coverage.cjs');

function fixture(t, { modules, assets }) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'rspack-analyze-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const build = path.join(dir, 'build.sqlite'); const recording = path.join(dir, 'recording.json'); const analysis = path.join(dir, 'coverage.sqlite'); const index = path.join(dir, 'index.sqlite');
  const db = createCapture(build, { context: '/fixture', buildHash: 'build-unit', graphAvailable: false });
  for (const module of modules) {
    const resource = module.resource || '/fixture/src/a.ts'; const text = module.content ?? 'export const value = 1;\n';
    db.prepare('INSERT INTO modules VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)').run(module.id, module.identifier || resource, module.layer ?? null, 'javascript/auto', resource, null,
      '["value"]', '["value"]', module.transformed ?? text, null, text, hash(module.transformed ?? text), hash(text), null);
    for (const chunk of module.chunks || ['main']) db.prepare('INSERT INTO module_chunks VALUES (?,?)').run(module.id, chunk);
  }
  const chunks = new Set();
  for (const asset of assets) {
    for (const chunk of asset.chunks || ['main']) chunks.add(chunk);
    db.prepare('INSERT INTO assets VALUES (?,?,?,?,?,?,?,?,?)').run(asset.name, asset.name, `/${asset.name}`, asset.text, hash(asset.text), asset.map ? JSON.stringify(asset.map) : null, null, JSON.stringify(asset.chunks || ['main']), 1);
  }
  for (const chunk of chunks) db.prepare('INSERT INTO chunks VALUES (?,?,?,?)').run(chunk, 1, '[]', '["main"]');
  setMeta(db, { status: 'complete' }); db.close();
  return { dir, build, recording, analysis, index,
    analyze(data, extra = []) { fs.writeFileSync(recording, JSON.stringify(data)); return main(['analyze', '--build', build, '--coverage', recording, '--out', analysis, ...extra]); },
    query(command, args = []) { return main([command, '--db', index, ...args]); },
    indexAnalysis() { return main(['index', '--coverage', analysis, '--out', index]); } };
}
const sourceMap = (content, mappings = [[[0, 0, 0, 0]]]) => ({ version: 3, sources: ['webpack:///./src/a.ts'], sourcesContent: [content], names: [], mappings: encode(mappings) });

test('analyze maps UTF-16 execution ranges to exact UTF-8 generated bytes and captured source lines', t => {
  const text = 'a😀b\nxyz'; const content = "const first = '😀';\nconst second = 2;\n";
  const f = fixture(t, { modules: [{ id: 'a', content }], assets: [{ name: 'main.js', text, map: sourceMap(content, [[[0, 0, 0, 0]], [[0, 0, 1, 0]]]) }] });
  const result = f.analyze([{ url: 'https://cdn.test/main.js?v=1', text, ranges: [{ start: 0, end: 3 }] }]);
  assert.equal(result.generated.emittedBytes, 10); assert.equal(result.generated.executedBytes, 5);
  assert.equal(result.generated.mappedBytes, 9); assert.equal(result.generated.unmappedBytes, 1);
  assert.equal(result.precision, 'unknown');
  fs.unlinkSync(f.build); fs.unlinkSync(f.recording); // Portable analysis owns the captured maps, source, graph and recording.
  f.indexAnalysis();
  const moduleId = f.query('modules').items[0].moduleId;
  const summary = f.query('coverage', ['--module', moduleId]);
  assert.equal(summary.generated.emittedBytes, 9); assert.equal(summary.generated.executedBytes, 5);
  const lines = f.query('coverage', ['--module', moduleId, '--view', 'lines', '--sort', 'line:asc']);
  assert.deepEqual(lines.items.map(item => item.runtimeState), ['executed', 'unexecuted']);
  const source = f.query('source', ['--source', lines.items[0].sourceId, '--module', moduleId]);
  assert.equal(source.content, content); assert.equal(source.coordinateSpace, 'resource');
  assert.equal(summary.retainedSource.executedBytes, Buffer.byteLength(content.split('\n')[0] + '\n'));
});

test('raw V8 nested zero blocks override positive outer functions; duplicate recordings union ranges', t => {
  assert.deepEqual(coveredRanges({ text: '0123456789', functions: [{ ranges: [
    { startOffset: 0, endOffset: 10, count: 1 }, { startOffset: 2, endOffset: 8, count: 0 }, { startOffset: 4, endOffset: 6, count: 2 },
  ] }] }), [{ start: 0, end: 2 }, { start: 4, end: 6 }, { start: 8, end: 10 }]);
  const f = fixture(t, { modules: [{ id: 'a' }], assets: [{ name: 'main.js', text: '0123456789', map: sourceMap('export const value = 1;\n') }] });
  const result = f.analyze([
    { url: '/main.js', text: '0123456789', ranges: [{ start: 0, end: 6 }] },
    { url: '/main.js', text: '0123456789', ranges: [{ start: 3, end: 8 }] },
  ]);
  assert.equal(result.generated.executedBytes, 8);
});

test('missing maps preserve generated totals and expose unavailable per-module attribution', t => {
  const f = fixture(t, { modules: [{ id: 'a' }], assets: [{ name: 'main.js', text: 'abc' }] });
  const result = f.analyze([{ url: '/main.js', text: 'abc', ranges: [{ start: 0, end: 2 }] }]);
  assert.equal(result.generated.mappedBytes, 0); assert.equal(result.generated.unmappedBytes, 3);
  f.indexAnalysis(); const module = f.query('modules').items[0]; assert.equal(module.coverage.generated, null);
  assert.equal(f.query('coverage', ['--module', module.moduleId, '--view', 'lines']).page.total, 0);
  assert.ok(f.query('gaps', ['--module', module.moduleId]).items.some(gap => gap.kind === 'coverage'));
});

test('analysis rejects a different build, invalid ranges and incomplete recordings without publishing partial output', t => {
  const f = fixture(t, { modules: [{ id: 'a' }], assets: [{ name: 'main.js', text: 'abc' }] });
  const initial = hash(fs.readFileSync(f.build));
  const cases = [
    [[{ url: '/main.js', text: 'wrong', ranges: [] }], 'INPUT_IDENTITY_MISMATCH'],
    [[{ url: '/main.js', text: 'abc', ranges: [{ start: 0, end: 4 }] }], 'INVALID_INPUT'],
    [{ kind: 'rspack-browser-recording', schemaVersion: 1, status: 'incomplete', scripts: [] }, 'INVALID_INPUT'],
    [[{ url: '/other.js', text: 'abc', ranges: [] }], 'INPUT_IDENTITY_MISMATCH'],
  ];
  for (const [data, code] of cases) {
    assert.throws(() => f.analyze(data), error => error.code === code);
    assert.equal(fs.existsSync(f.analysis), false); assert.equal(fs.readdirSync(f.dir).some(name => name.endsWith('.incomplete')), false);
    assert.equal(hash(fs.readFileSync(f.build)), initial);
  }
  assert.throws(() => f.analyze({ schemaVersion: 1, kind: 'rspack-browser-recording', status: 'complete', precision: 'per-block', scripts: [] }, ['--precision', 'per-function']), error => error.code === 'INPUT_IDENTITY_MISMATCH');
});

test('shared resource instances use chunk evidence; ambiguous same-asset instances stay unknown', t => {
  const content = 'export const value = 1;\n'; const map = sourceMap(content);
  const precise = fixture(t, { modules: [{ id: 'a', identifier: 'loader-a!/fixture/src/a.ts', chunks: ['a'] }, { id: 'b', identifier: 'loader-b!/fixture/src/a.ts', chunks: ['b'] }],
    assets: [{ name: 'a.js', text: 'aaa', map, chunks: ['a'] }, { name: 'b.js', text: 'bbb', map, chunks: ['b'] }] });
  precise.analyze([{ url: '/a.js', text: 'aaa', ranges: [] }]); precise.indexAnalysis();
  const rows = precise.query('modules').items;
  assert.ok(rows.every(row => row.coverage.generated.emittedBytes === 3));
  assert.equal(rows.find(row => row.identifier.startsWith('loader-a')).coverage.generated.unexecutedBytes, 3);
  assert.equal(rows.find(row => row.identifier.startsWith('loader-b')).loaded, false);
  const ambiguous = fixture(t, { modules: [{ id: 'a', layer: 'a' }, { id: 'b', layer: 'b' }], assets: [{ name: 'main.js', text: 'aaa', map }] });
  ambiguous.analyze([{ url: '/main.js', text: 'aaa', ranges: [] }]); ambiguous.indexAnalysis();
  assert.ok(ambiguous.query('modules').items.every(row => row.coverage.generated === null && row.coverage.retainedSource === null));
  assert.ok(ambiguous.query('gaps', ['--kind', 'shared-source']).page.total >= 2);
});

test('loader-map text keeps map-source identity when its content differs from the captured resource', t => {
  const original = 'export const value: number = 1;\n'; const intermediate = 'export const value = 1;\n';
  const f = fixture(t, { modules: [{ id: 'a', content: original, transformed: intermediate }], assets: [{ name: 'main.js', text: 'aaa', map: sourceMap(intermediate) }] });
  f.analyze([{ url: '/main.js', text: 'aaa', ranges: [] }]); f.indexAnalysis();
  const moduleId = f.query('modules').items[0].moduleId;
  const line = f.query('coverage', ['--module', moduleId, '--view', 'lines']).items[0];
  const source = f.query('source', ['--source', line.sourceId]); assert.equal(source.coordinateSpace, 'map-source'); assert.equal(source.content, intermediate);
});

test('indexed source maps map only their covered sections; malformed maps retain an explicit gap', t => {
  const content = 'export const value = 1;\n';
  const indexed = { version: 3, sections: [{ offset: { line: 1, column: 0 }, map: sourceMap(content) }] };
  const f = fixture(t, { modules: [{ id: 'a' }], assets: [{ name: 'main.js', text: 'foo\nbar', map: indexed }] });
  const result = f.analyze([{ url: '/main.js', text: 'foo\nbar', ranges: [] }]); assert.equal(result.generated.mappedBytes, 3); assert.equal(result.generated.unmappedBytes, 4);
  const bad = fixture(t, { modules: [{ id: 'a' }], assets: [{ name: 'main.js', text: 'abc', map: sourceMap(content, [[[100, 0, 0, 0]]]) }] });
  const analyzed = bad.analyze([{ url: '/main.js', text: 'abc', ranges: [] }]); assert.equal(analyzed.generated.unmappedBytes, 3); assert.equal(analyzed.counts.gaps, 1);
  bad.indexAnalysis(); assert.ok(bad.query('gaps').items.some(gap => gap.kind === 'build'));
});

test('a script seen only in Network remains unknown, never a zero-execution conclusion', t => {
  const content = 'export const value = 1;\n'; const map = sourceMap(content);
  const f = fixture(t, { modules: [{ id: 'a', chunks: ['a'] }, { id: 'b', resource: '/fixture/src/b.ts', content, chunks: ['b'] }],
    assets: [{ name: 'a.js', text: 'aaa', map, chunks: ['a'] }, { name: 'b.js', text: 'bbb', map: { ...map, sources: ['webpack:///./src/b.ts'] }, chunks: ['b'] }] });
  const result = f.analyze({ schemaVersion: 1, kind: 'rspack-browser-recording', status: 'complete', precision: 'per-block',
    scripts: [{ url: '/a.js', text: 'aaa', ranges: [] }], network: [{ url: '/b.js', type: 'Script', status: 200 }] });
  assert.equal(result.generated.loadedBytes, null); assert.equal(result.generated.executedBytes, null);
  f.indexAnalysis(); const b = f.query('modules', ['--search', '/b.ts']).items[0];
  assert.equal(b.loaded, null); assert.equal(b.coverage.generated.unexecutedBytes, null); assert.equal(b.coverage.generated.emittedBytes, 3);
  assert.equal(f.query('coverage', ['--module', b.moduleId, '--view', 'lines']).items[0].runtimeState, 'unknown');
  assert.ok(f.query('gaps').items.some(item => item.kind === 'build'));
});

test('status stays small when a recording contains many ignored third-party scripts', t => {
  const f = fixture(t, { modules: [{ id: 'a' }], assets: [{ name: 'main.js', text: 'aaa', map: sourceMap('export const value = 1;\n') }] });
  f.analyze([{ url: '/main.js', text: 'aaa', ranges: [] }, ...Array.from({ length: 1000 }, (_, i) => ({ url: `https://third-party.test/${'x'.repeat(100)}/${i}.js`, text: '', ranges: [] }))]);
  f.indexAnalysis(); const status = f.query('status');
  assert.equal(status.recording.ignoredScripts, 1000); assert.ok(Buffer.byteLength(JSON.stringify(status)) < 4096);
  assert.equal(f.query('gaps', ['--kind', 'ignored-coverage']).page.total, 1000);
});
