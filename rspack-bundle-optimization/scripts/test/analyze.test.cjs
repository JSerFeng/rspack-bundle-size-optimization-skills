test('a script seen only in Network remains unknown, exposes observed subtotal, and categorizes gaps by kind', t => {
  const content = 'export const value = 1;\n'; const map = sourceMap(content);
  const f = fixture(t, { modules: [{ id: 'a', chunks: ['a'] }, { id: 'b', resource: '/fixture/src/b.ts', content, chunks: ['b'] }],
    assets: [{ name: 'a.js', text: 'aaa', map, chunks: ['a'] }, { name: 'b.js', text: 'bbb', map: { ...map, sources: ['webpack:///./src/b.ts'] }, chunks: ['b'] }] });
  const result = f.indexDirect({ schemaVersion: 1, kind: 'rspack-browser-recording', status: 'complete', precision: 'per-block',
    scripts: [{ url: '/a.js', text: 'aaa', ranges: [{ start: 0, end: 1 }] }], network: [{ url: '/b.js', type: 'Script', status: 200 }] });
  assert.equal(result.generated.loadedBytes, null); assert.equal(result.generated.executedBytes, null);
  assert.deepEqual(result.generated.observed, {
    matchedAssets: 1, unknownAssets: 1, unknownEmittedBytes: 3, loadedBytes: 3, executedBytes: 1, unusedBytes: 2,
  });
  const b = f.query('modules', ['--search', 'b.ts']).items[0];
  assert.equal(b.loaded, null); assert.equal(b.coverage.generated.unexecutedBytes, null); assert.equal(b.coverage.generated.emittedBytes, 3);
  assert.equal(f.query('source', ['--module', b.moduleId, '--state', 'unknown']).items[0].runtimeState, 'unknown');
  assert.ok(f.query('status', ['--gaps', '--kind', 'network-without-coverage']).items.some(item => item.kind === 'network-without-coverage'));
  const status = f.query('status');
  assert.ok(status.gapKinds.some(k => k.kind === 'network-without-coverage' && k.count === 1));
  const statusText = formatText('status', status);
  assert.ok(statusText.includes('observed (1 matched assets):'));
  assert.ok(statusText.includes('network-without-coverage=1'));
});

test('source --unexecuted includes partially executed lines (gu > 0) and explains empty strict queries', t => {
  // Single source line maps to 20 bytes generated: first 2 bytes executed, 18 bytes unexecuted (partial line).
  const text = 'fn(){/*unexecuted*/}';
  const content = 'export const handler = () => { return "never-called"; };\n';
  const f = fixture(t, { modules: [{ id: 'a', content }], assets: [{ name: 'main.js', text, map: sourceMap(content, [[[0, 0, 0, 0], [5, 0, 0, 20]]]) }] });
  f.indexDirect([{ url: '/main.js', text, ranges: [{ start: 0, end: 2 }] }]);
  const mod = f.query('modules').items[0].moduleId;

  const unexec = f.query('source', ['--module', mod, '--unexecuted']);
  assert.equal(unexec.items.length, 1);
  assert.equal(unexec.items[0].partial, true);
  assert.equal(unexec.items[0].generated.executedBytes, 2);
  assert.equal(unexec.items[0].generated.unexecutedBytes, 18);
  assert.equal(unexec.items[0].sourceRangeCount, 2);
  assert.ok(formatText('source', unexec).includes('| partial |'));

  const partialOnly = f.query('source', ['--module', mod, '--state', 'partial']);
  assert.equal(partialOnly.items.length, 1);

  const strictUnexec = f.query('source', ['--module', mod, '--state', 'unexecuted']);
  assert.equal(strictUnexec.items.length, 0);
  assert.equal(strictUnexec.lineSummary.partialLines, 1);
  assert.ok(formatText('source', strictUnexec).includes('partial=1'));

  const win = f.query('source', ['--module', mod]);
  assert.ok(formatText('source', win).includes('PART'));
});

test('status stays small when a recording contains many ignored third-party scripts', t => {
  const f = fixture(t, { modules: [{ id: 'a' }], assets: [{ name: 'main.js', text: 'aaa', map: sourceMap('export const value = 1;\n') }] });
  f.indexDirect([{ url: '/main.js', text: 'aaa', ranges: [] }, ...Array.from({ length: 1000 }, (_, i) => ({ url: `https://third-party.test/${'x'.repeat(100)}/${i}.js`, text: '', ranges: [] }))]);
  const status = f.query('status');
  assert.equal(status.recording.ignoredScripts, 1000); assert.ok(Buffer.byteLength(JSON.stringify(status)) < 4096);
  assert.equal(f.query('status', ['--gaps', '--kind', 'ignored-coverage']).page.total, 1000);
});
